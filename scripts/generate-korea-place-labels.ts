/**
 * Read-only: median lat/lng per 시·군 from poi addresses → lib/koreaPlaceLabels.ts
 *
 *   npx tsx scripts/generate-korea-place-labels.ts
 *
 * Supplements OpenMapTiles place labels when 군/시 anchors are sparse at far zoom.
 * Never prints connection strings or secrets.
 */
import fs from "node:fs";
import { spawnSync } from "node:child_process";
import path from "node:path";

const ROOT = process.cwd();
const OUT = path.join(ROOT, "lib/koreaPlaceLabels.ts");
const PY = path.join(ROOT, "scripts/localdata/.venv/bin/python");

type Row = {
  name: string;
  kind: "si" | "gun";
  lng: number;
  lat: number;
  n: number;
};

function loadRows(): Row[] {
  const dbUrl = fs
    .readFileSync(path.join(ROOT, "scripts/localdata/.db_url"), "utf8")
    .trim();
  const code = `
import json, psycopg2
conn = psycopg2.connect(${JSON.stringify(dbUrl)})
cur = conn.cursor()
cur.execute("""
WITH addr AS (
  SELECT
    lat::float8 AS lat,
    lng::float8 AS lng,
    COALESCE(NULLIF(TRIM(road_address), ''), NULLIF(TRIM(jibun_address), '')) AS address
  FROM poi
  WHERE lat IS NOT NULL AND lng IS NOT NULL
    AND lat BETWEEN 33 AND 39.5 AND lng BETWEEN 124 AND 132
),
tagged AS (
  SELECT
    lat, lng, address,
    (regexp_match(
      address,
      '(경기도|강원특별자치도|강원도|충청북도|충청남도|전북특별자치도|전라북도|전라남도|경상북도|경상남도|제주특별자치도)\\\\s+([가-힣]+[시군])'
    ))[2] AS place
  FROM addr
  WHERE address IS NOT NULL
)
SELECT
  place AS name,
  CASE WHEN place LIKE '%군' THEN 'gun' ELSE 'si' END AS kind,
  round(percentile_cont(0.5) WITHIN GROUP (ORDER BY lng)::numeric, 4) AS lng,
  round(percentile_cont(0.5) WITHIN GROUP (ORDER BY lat)::numeric, 4) AS lat,
  count(*)::int AS n
FROM tagged
WHERE place IS NOT NULL
  AND place NOT IN (
    '서울특별시','부산광역시','대구광역시','인천광역시','광주광역시',
    '대전광역시','울산광역시','세종특별자치시'
  )
GROUP BY place
HAVING count(*) >= 8
ORDER BY kind, place
""");
rows = [{"name": r[0], "kind": r[1], "lng": float(r[2]), "lat": float(r[3]), "n": int(r[4])} for r in cur.fetchall()]
print(json.dumps(rows, ensure_ascii=False))
conn.close()
`;
  const r = spawnSync(PY, ["-c", code], {
    encoding: "utf8",
    maxBuffer: 32 * 1024 * 1024,
  });
  if (r.status !== 0) {
    throw new Error(`python failed: ${r.stderr || r.stdout}`);
  }
  return JSON.parse(r.stdout) as Row[];
}

function displayName(name: string, kind: "si" | "gun"): string {
  // Keep 군 suffix (고성군×2). Keep 광주시. Strip trailing 시 otherwise.
  if (kind === "gun") return name;
  if (name === "광주시") return "광주시";
  if (name.endsWith("시") && name.length > 2) return name.slice(0, -1);
  return name;
}

function main() {
  const rows = loadRows();
  const body = rows
    .map(
      (r) => `  {
    "name": ${JSON.stringify(displayName(r.name, r.kind))},
    "full": ${JSON.stringify(r.name)},
    "kind": ${JSON.stringify(r.kind)},
    "lng": ${r.lng},
    "lat": ${r.lat}
  }`,
    )
    .join(",\n");

  const src = `/**
 * Nationwide 시·군 label anchors for MapLibre far/mid zoom overlay.
 * Generated by scripts/generate-korea-place-labels.ts (poi median coords).
 * Do not edit by hand — re-run the script instead.
 */

export type KoreaPlaceLabel = {
  name: string;
  full: string;
  kind: "si" | "gun";
  lng: number;
  lat: number;
};

export const KOREA_PLACE_LABELS: readonly KoreaPlaceLabel[] = [
${body}
];

export function koreaPlaceLabelsGeoJson(): GeoJSON.FeatureCollection {
  return {
    type: "FeatureCollection",
    features: KOREA_PLACE_LABELS.map((p, i) => ({
      type: "Feature",
      id: i,
      properties: {
        name: p.name,
        full: p.full,
        kind: p.kind,
      },
      geometry: {
        type: "Point",
        coordinates: [p.lng, p.lat],
      },
    })),
  };
}
`;
  fs.writeFileSync(OUT, src, "utf8");
  console.log(`Wrote ${rows.length} place labels → ${path.relative(ROOT, OUT)}`);
}

main();
