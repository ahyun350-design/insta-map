/**
 * Dedupe korea-landmarks.geojson: similar names within 500m → keep one
 * (lower tier number wins, then wikidata, then height/levels).
 *
 *   npx tsx scripts/dedupe-korea-landmarks.ts
 *
 * Also writes lib/mapSurface/koreaLandmarkNameBlocklist.ts for OMT name hiding.
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const IN = path.join(ROOT, "public/map/korea-landmarks.geojson");
const OUT = IN;
const BLOCKLIST = path.join(
  ROOT,
  "lib/mapSurface/koreaLandmarkNameBlocklist.ts",
);

type Feat = {
  type: "Feature";
  properties: {
    name: string;
    tier: number;
    wikidata?: string;
    height?: number;
    levels?: number;
    kind?: string;
  };
  geometry: { type: "Point"; coordinates: [number, number] };
};

function normalizeName(s: string): string {
  return String(s || "")
    .replace(/\s+/g, "")
    .replace(/[()（）\[\]【】]/g, "")
    .toLowerCase();
}

function namesSimilar(a: string, b: string): boolean {
  const na = normalizeName(a);
  const nb = normalizeName(b);
  if (!na || !nb) return false;
  if (na === nb) return true;
  if (na.length < 3 || nb.length < 3) return false;
  return na.includes(nb) || nb.includes(na);
}

function haversineM(
  lng1: number,
  lat1: number,
  lng2: number,
  lat2: number,
): number {
  const R = 6371000;
  const toR = (d: number) => (d * Math.PI) / 180;
  const dLat = toR(lat2 - lat1);
  const dLng = toR(lng2 - lng1);
  const a =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(toR(lat1)) * Math.cos(toR(lat2)) * Math.sin(dLng / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(a));
}

function score(f: Feat): number {
  let s = 0;
  s += (4 - (f.properties.tier || 3)) * 10000;
  if (f.properties.wikidata) s += 1000;
  s += f.properties.height ?? 0;
  s += (f.properties.levels ?? 0) * 10;
  s += Math.min(normalizeName(f.properties.name).length, 40);
  return s;
}

function dedupe(features: Feat[], radiusM = 500): Feat[] {
  const sorted = [...features].sort((a, b) => score(b) - score(a));
  const kept: Feat[] = [];
  for (const f of sorted) {
    const [lng, lat] = f.geometry.coordinates;
    const clash = kept.some((k) => {
      if (!namesSimilar(f.properties.name, k.properties.name)) return false;
      const [klng, klat] = k.geometry.coordinates;
      return haversineM(lng, lat, klng, klat) <= radiusM;
    });
    if (!clash) kept.push(f);
  }
  return kept;
}

function main() {
  const raw = JSON.parse(fs.readFileSync(IN, "utf8")) as {
    type: string;
    features: Feat[];
  };
  const before = raw.features.length;
  const beforeTiers = { 1: 0, 2: 0, 3: 0 };
  for (const f of raw.features) {
    const t = f.properties.tier as 1 | 2 | 3;
    beforeTiers[t] = (beforeTiers[t] || 0) + 1;
  }

  const afterFeatures = dedupe(raw.features);
  const afterTiers = { 1: 0, 2: 0, 3: 0 };
  for (const f of afterFeatures) {
    const t = f.properties.tier as 1 | 2 | 3;
    afterTiers[t] = (afterTiers[t] || 0) + 1;
  }

  const fc = { type: "FeatureCollection", features: afterFeatures };
  fs.writeFileSync(OUT, JSON.stringify(fc));
  const bytes = Buffer.byteLength(JSON.stringify(fc), "utf8");

  // Blocklist: display names + normalized variants for OMT match
  const names = new Set<string>();
  const addName = (n0: string) => {
    const n = String(n0 || "").trim();
    if (!n) return;
    names.add(n);
    const stripped = n
      .replace(/\s*\([^)]*\)\s*/g, "")
      .replace(/\s*（[^）]*）\s*/g, "")
      .trim();
    if (stripped) names.add(stripped);
  };
  for (const f of afterFeatures) addName(f.properties.name);

  // Also hide OMT labels that duplicate korea_major_labels landmarks/mountains
  try {
    const majorPath = path.join(ROOT, "lib/koreaMajorLabels.ts");
    const majorSrc = fs.readFileSync(majorPath, "utf8");
    for (const m of majorSrc.matchAll(/name:\s*"([^"]+)"[^}]*kind:\s*"(landmark|mountain)"/g)) {
      addName(m[1]!);
    }
  } catch {
    /* ignore */
  }
  const list = [...names].sort((a, b) => a.localeCompare(b, "ko"));
  const body = `/**
 * Auto-generated by scripts/dedupe-korea-landmarks.ts — do not edit by hand.
 * Used to hide OpenMapTiles POI/place labels that duplicate korea-landmarks names.
 */
export const KOREA_LANDMARK_NAME_BLOCKLIST: string[] = ${JSON.stringify(list, null, 2)};
`;
  fs.writeFileSync(BLOCKLIST, body);

  console.log(
    JSON.stringify(
      {
        before,
        after: afterFeatures.length,
        removed: before - afterFeatures.length,
        beforeTiers,
        afterTiers,
        bytes,
        blocklistNames: list.length,
      },
      null,
      2,
    ),
  );
}

main();
